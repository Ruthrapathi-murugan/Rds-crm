import { z } from "zod";
import { PAYMENT_METHODS, TAX_MODES } from "@/lib/constants";
import {
  dateInput,
  moneyInput,
  objectId,
  optionalObjectId,
  optionalText,
  positiveMoneyInput,
  requiredText,
} from "./common";

/** Percentage string → basis points; "" means 0%. */
const taxRateInput = z
  .union([z.string(), z.number()])
  .optional()
  .transform((value, ctx) => {
    if (value === undefined || value === "") return 0;
    const text = String(value).trim();
    if (!/^\d{1,3}(\.\d{1,2})?$/.test(text)) {
      ctx.addIssue({ code: "custom", message: "Choose a tax rate" });
      return z.NEVER;
    }
    const [whole, fraction = ""] = text.split(".");
    const bps = Number(whole) * 100 + Number(fraction.padEnd(2, "0"));
    if (bps > 10_000) {
      ctx.addIssue({ code: "custom", message: "Tax rate cannot exceed 100%" });
      return z.NEVER;
    }
    return bps;
  });

export const lineItemInput = z
  .object({
    service: optionalObjectId,
    description: requiredText("Description", 1000),
    sacCode: z
      .string()
      .trim()
      .refine((v) => v === "" || /^\d{4,8}$/.test(v), "SAC/HSN code is 4–8 digits")
      .optional()
      .transform((v) => v ?? ""),
    quantity: z.coerce
      .number({ error: "Enter a quantity" })
      .int("Quantity must be a whole number")
      .min(1, "Quantity must be at least 1")
      .max(100_000, "Quantity is too large"),
    unitPrice: moneyInput,
    discount: moneyInput,
    taxRate: taxRateInput,
  })
  .superRefine((line, ctx) => {
    if (line.discount > line.quantity * line.unitPrice) {
      ctx.addIssue({ code: "custom", path: ["discount"], message: "Discount cannot exceed the line amount" });
    }
  });
export type LineItemInput = z.input<typeof lineItemInput>;

const documentBase = {
  customer: objectId.describe("customer"),
  taxMode: z.enum(TAX_MODES),
  items: z.array(lineItemInput).min(1, "Add at least one line item").max(50, "A document can have at most 50 lines"),
  terms: optionalText(5000),
  notes: optionalText(2000),
};

export const quotationFormSchema = z
  .object({
    ...documentBase,
    lead: optionalObjectId,
    project: optionalObjectId,
    issueDate: dateInput,
    validUntil: dateInput,
  })
  .refine((v) => v.validUntil.getTime() >= v.issueDate.getTime(), {
    path: ["validUntil"],
    message: "Valid-until date cannot be before the quotation date",
  });
export type QuotationFormInput = z.input<typeof quotationFormSchema>;
export type QuotationFormData = z.output<typeof quotationFormSchema>;

export const invoiceFormSchema = z
  .object({
    ...documentBase,
    project: optionalObjectId,
    issueDate: dateInput,
    dueDate: dateInput,
  })
  .refine((v) => v.dueDate.getTime() >= v.issueDate.getTime(), {
    path: ["dueDate"],
    message: "Due date cannot be before the invoice date",
  });
export type InvoiceFormInput = z.input<typeof invoiceFormSchema>;
export type InvoiceFormData = z.output<typeof invoiceFormSchema>;

export const quotationStatusSchema = z.object({
  status: z.enum(["draft", "sent", "accepted", "rejected"]),
});

export const cancelInvoiceSchema = z.object({
  reason: requiredText("Reason", 500),
});

export const paymentFormSchema = z.object({
  customer: optionalObjectId,
  invoice: optionalObjectId,
  project: optionalObjectId,
  paidAt: dateInput,
  amount: positiveMoneyInput,
  method: z.enum(PAYMENT_METHODS, { error: "Choose a payment method" }),
  transactionReference: optionalText(120),
  notes: optionalText(1000),
  /** Generated by the form when it opens; resubmitting the same form cannot record twice. */
  idempotencyKey: z.string().trim().min(8).max(100),
});
export type PaymentFormInput = z.input<typeof paymentFormSchema>;
export type PaymentFormData = z.output<typeof paymentFormSchema>;

export const voidPaymentSchema = z.object({
  reason: requiredText("Reason", 500),
});

export const emailDocumentSchema = z.object({
  to: z.email("Enter a valid email address").trim().max(200),
  message: optionalText(2000),
});
